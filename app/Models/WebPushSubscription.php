<?php

namespace App\Models;

use Database\Factories\WebPushSubscriptionFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\Hidden;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

/**
 * @property int $id
 * @property int $user_id
 * @property string $endpoint
 * @property string $public_key
 * @property string $auth_token
 */
#[Fillable(['user_id', 'endpoint_hash', 'endpoint', 'public_key', 'auth_token'])]
#[Hidden(['endpoint_hash', 'endpoint', 'public_key', 'auth_token'])]
class WebPushSubscription extends Model
{
    /** @use HasFactory<WebPushSubscriptionFactory> */
    use HasFactory;

    /** @return BelongsTo<User, $this> */
    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    /** @return array<string, string> */
    protected function casts(): array
    {
        return [
            'endpoint' => 'encrypted',
            'public_key' => 'encrypted',
            'auth_token' => 'encrypted',
        ];
    }
}
